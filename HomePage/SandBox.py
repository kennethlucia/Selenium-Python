def parse_csv_with_headers(csv_file_path):
    """
    This method was generated by Claude

    Parse a CSV file using the first line as keys and create dictionaries
    for the next 5 lines of data.

    Args:
        csv_file_path (str): Path to the CSV file

    Returns:
        list: List of dictionaries, where each dictionary uses header values as keys
    """
    with open(csv_file_path, 'r') as fp:
        lines = sum(1 for line in fp)
    try:
        with open(csv_file_path, 'r') as file:
            # Read and process header line
            headers = [h.strip().strip('"') for h in next(file).strip().split(',')]
            # Process exactly 5 data lines
            return [
                dict(zip(headers, [v.strip().strip('"') for v in line.strip().split(',')]))
                for line in (next(file) for _ in range(lines - 1))
            ]

    except FileNotFoundError:
        print(f"Error: File '{csv_file_path}' not found.")
    except StopIteration:
        print("Error: File does not contain enough lines.")
    except Exception as e:
        print(f"Error occurred: {str(e)}")

    return []


